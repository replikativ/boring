(require '[clojure.string] '[boring.core :as b])
(defn h [s] (let [s (clojure.string/replace s " " "")]
              (byte-array (map #(unchecked-byte (Integer/parseInt (apply str %) 16)) (partition 2 s)))))
(defn t [label s]
  (print (format "%-42s %-26s " label s))
  (try (let [v (b/decode (h s))]
         (println (pr-str v) "| class=" (some-> v class .getSimpleName)
                  "| reenc=" (try (apply str (map #(format "%02x" (bit-and % 0xff)) (b/encode v))) (catch Exception e (str "ENC-ERR " (.getMessage e))))))
       (catch Exception e (println "ERR" (:type (ex-data e)) "|" (.getMessage e)))))
(println "--- tag 40 over plain byte string")
(t "40([[2], h'a363'])"          "d828 82 8102 42a363")
(t "40([[3], h'ff0001'])"        "d828 82 8103 43ff0001")
(println "--- tag 30 rational")
(t "30([5,1])"                   "d81e 82 05 01")
(t "30([40,10])"                 "d81e 82 1828 0a")
(t "30([39,-13])"                "d81e 82 1827 2c")
(t "30([1,0])"                   "d81e 82 01 00")
(t "30([1,-2])"                  "d81e 82 01 21")
(println "--- shaped array 39649 integer keys")
(t "39649([[4,4],[]])"           "d9 9ae1 82 82 0404 80")
(t "39649([[1],[[7]]])"          "d9 9ae1 82 8101 81 8107")
(println "--- tag 27 sorted-set single incomparable")
