(t "27(clojure/sorted-set [h'46'])" "d81b 82 72 636c6f6a7572652f736f727465642d736574 81 4146")
(t "27(clojure/sorted-map {{}:{}})" "d81b 82 72 636c6f6a7572652f736f727465642d6d6170 a1 a0 a0")
(println "--- tag 35 empty regex")
(t "35(\"\")"                    "d823 60")
